# Лоты с расчётным риском выше этого порога вообще не присылаются —
# отсеиваются автоматически, чтобы не засорять чат сомнительными вариантами.
#
# Важно про шкалу: формула риска (scoring.compute_risk) стартует с базовых
# 45 баллов и добавляет/вычитает баллы за известные факторы. Для лота, по
# которому бот НЕ смог автоматически определить комплектность и продавец
# новый (самый частый случай для обычных частных объявлений без слов
# "коробка"/"документы" и без истории отзывов) — риск получается около 65,
# и это нормальный, не обязательно плохой лот, а просто "мало сведений".
# Порог 70 пропускает такие типичные лоты, но всё ещё отсеивает по-настоящему
# рискованные (явные сомнения в подлинности, низкая ликвидность и т.д.,
# которые в сумме дают за 80). Если поставить порог слишком низко (например,
# 30) — почти ни один лот не пройдёт фильтр, и предложений не будет вообще,
# даже если на Kufar они есть.
MAX_RISK_TO_SUGGEST = int(_env("MAX_RISK_TO_SUGGEST", "70"))

