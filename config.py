# Сколько НОВЫХ (ранее не встреченных) объявлений детально проверять за один
# проход сканирования. Ограничение защищает от перегрузки при первом запуске,
# когда "новыми" окажутся сразу все объявления на странице категории. Бот
# смотрит на все бренды часов, а не только Casio, так что новых объявлений в
# целом будет больше — при желании увеличьте это число.
